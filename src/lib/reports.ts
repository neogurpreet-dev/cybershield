import type { Incident } from '../types';
import { downloadFile, formatDateTime } from './format';

const SEV = { low: 'Low', medium: 'Medium', high: 'High', critical: 'Critical' } as const;
const STATUS = { open: 'Open', investigating: 'Investigating', resolved: 'Resolved' } as const;

function meta(inc: Incident, owner: string): [string, string][] {
  return [
    ['Incident', `#${inc.number}`],
    ['Status', STATUS[inc.status]],
    ['Severity', SEV[inc.severity]],
    ['Category', inc.category],
    ['Reported', formatDateTime(inc.createdAt)],
    ['Resolved', inc.resolvedAt ? formatDateTime(inc.resolvedAt) : 'Not yet'],
    ['Owner', owner],
  ];
}

export function incidentText(inc: Incident, owner: string): string {
  const lines = [
    `CyberShield incident report #${inc.number}: ${inc.title}`,
    '',
    ...meta(inc, owner).map(([k, v]) => `${k}: ${v}`),
    '',
    'Summary',
    inc.summary,
    ...(inc.details ? ['', 'Details', inc.details] : []),
    '',
    'Action checklist',
    ...inc.checklist.map((c) => `[${c.done ? 'x' : ' '}] ${c.text}`),
    '',
    'Timeline',
    ...inc.timeline.map((t) => `${formatDateTime(t.at)}: ${t.text}`),
  ];
  return lines.join('\n');
}

export async function exportIncidentPdf(inc: Incident, owner: string) {
  const { jsPDF } = await import('jspdf');
  const pdf = new jsPDF({ unit: 'pt', format: 'a4' });
  const W = pdf.internal.pageSize.getWidth();
  const H = pdf.internal.pageSize.getHeight();
  const M = 48;
  let y = M;

  const ensure = (h: number) => {
    if (y + h > H - M) {
      pdf.addPage();
      y = M;
    }
  };
  const para = (text: string, size = 10, style: 'normal' | 'bold' = 'normal', color = 30) => {
    pdf.setFont('helvetica', style);
    pdf.setFontSize(size);
    pdf.setTextColor(color);
    const lines = pdf.splitTextToSize(text, W - M * 2) as string[];
    lines.forEach((ln) => {
      ensure(size * 1.4);
      pdf.text(ln, M, y);
      y += size * 1.4;
    });
  };
  const heading = (text: string) => {
    y += 10;
    ensure(30);
    pdf.setDrawColor(8, 145, 178);
    pdf.setLineWidth(1);
    pdf.line(M, y, W - M, y);
    y += 16;
    para(text, 12, 'bold', 15);
  };

  pdf.setFillColor(8, 145, 178);
  pdf.rect(0, 0, W, 6, 'F');
  para('CYBERSHIELD INCIDENT REPORT', 9, 'bold', 110);
  para(`#${inc.number}  ${inc.title}`, 17, 'bold', 15);
  y += 6;
  meta(inc, owner).forEach(([k, v]) => {
    ensure(14);
    pdf.setFont('helvetica', 'bold');
    pdf.setFontSize(9);
    pdf.setTextColor(100);
    pdf.text(k.toUpperCase(), M, y);
    pdf.setFont('helvetica', 'normal');
    pdf.setFontSize(10);
    pdf.setTextColor(30);
    pdf.text(String(v), M + 90, y);
    y += 15;
  });

  heading('Summary');
  para(inc.summary || '—');
  if (inc.details) {
    heading('Details');
    para(inc.details);
  }
  heading('Action checklist');
  inc.checklist.forEach((c) => para(`${c.done ? '[x]' : '[  ]'}  ${c.text}`));
  heading('Timeline');
  inc.timeline.forEach((t) => para(`${formatDateTime(t.at)}  ${t.text}`));

  const pages = pdf.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    pdf.setPage(i);
    pdf.setFontSize(8);
    pdf.setTextColor(140);
    pdf.text(`Generated by CyberShield on ${new Date().toLocaleString()}  ·  Page ${i} of ${pages}`, M, H - 24);
  }
  pdf.save(`CyberShield_Incident_${inc.number}.pdf`);
}

export async function exportIncidentDocx(inc: Incident, owner: string) {
  const { Document, Packer, Paragraph, HeadingLevel, TextRun, Table, TableRow, TableCell, WidthType } = await import('docx');
  const cell = (text: string, bold = false) =>
    new TableCell({ width: { size: 50, type: WidthType.PERCENTAGE }, children: [new Paragraph({ children: [new TextRun({ text, bold })] })] });
  const doc = new Document({
    creator: 'CyberShield',
    title: `Incident #${inc.number}`,
    sections: [
      {
        children: [
          new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun(`Incident #${inc.number}: ${inc.title}`)] }),
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: meta(inc, owner).map(([k, v]) => new TableRow({ children: [cell(k, true), cell(v)] })),
          }),
          new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun('Summary')] }),
          ...inc.summary.split('\n').map((l) => new Paragraph(l)),
          ...(inc.details
            ? [new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun('Details')] }), ...inc.details.split('\n').map((l) => new Paragraph(l))]
            : []),
          new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun('Action checklist')] }),
          ...inc.checklist.map((c) => new Paragraph({ children: [new TextRun(`${c.done ? '☑' : '☐'}  ${c.text}`)] })),
          new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun('Timeline')] }),
          ...inc.timeline.map((t) => new Paragraph({ children: [new TextRun({ text: `${formatDateTime(t.at)}  `, bold: true }), new TextRun(t.text)] })),
          new Paragraph({ children: [new TextRun({ text: `Generated by CyberShield on ${new Date().toLocaleString()}`, italics: true, size: 16 })] }),
        ],
      },
    ],
  });
  const blob = await Packer.toBlob(doc);
  downloadFile(`CyberShield_Incident_${inc.number}.docx`, blob, 'application/vnd.openxmlformats-officedocument.wordprocessingml.document');
}
